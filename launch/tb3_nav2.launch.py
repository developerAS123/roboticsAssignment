#!/usr/bin/env python3
"""Launch TurtleBot3 simulation together with the full Nav2 stack.
Uses the map generated by Phase 7 (office_map.yaml).
"""
import os
from launch import LaunchDescription
from launch.actions import IncludeLaunchDescription, SetLaunchConfiguration, LogInfo
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import PathJoinSubstitution, LaunchConfiguration

def generate_launch_description():
    # Simulation (headless, use_sim_time)
    sim = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(PathJoinSubstitution([
            '/workspace/launch', 'tb3_sim.launch.py'
        ])),
        launch_arguments={
            'headless': 'true',
            'use_sim_time': 'true',
        }.items(),
    )

    # Nav2 bringup (navigation_launch)
    nav2 = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(PathJoinSubstitution([
            '/opt/ros/jazzy/share/nav2_bringup/launch', 'navigation_launch.py'
        ])),
        launch_arguments={
            'use_sim_time': 'true',
            'map': '/workspace/maps/office_map.yaml',
            'autostart': 'true',
            'params_file': '/workspace/config/nav2_params.yaml',
        }.items(),
    )

    ld = LaunchDescription()
    ld.add_action(sim)
    ld.add_action(nav2)
    ld.add_action(LogInfo(msg='Nav2 stack launched with map /workspace/maps/office_map.yaml'))
    return ld

